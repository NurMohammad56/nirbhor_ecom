test("deactivated combos cannot be purchased from a previously saved bag", async ({ page }) => {
  await page.goto("/offers");
  await page.getByRole("button", { name: "সকালের সঙ্গী কম্বো ব্যাগে যোগ করুন", exact: true }).click();
  await page.getByRole("button", { name: bn("Close bag"), exact: true }).click();
  await page.goto("/admin/offers");
  await page.getByRole("checkbox", { name: "সকালের সঙ্গী চালু রাখুন", exact: true }).uncheck();
  await page.goto("/cart");
  await expect(page.locator(".combo-cart-group [role=alert]")).toContainText("অফারটি বদলেছে অথবা শেষ হয়েছে");
  await page.goto("/checkout");
  await page.getByLabel(bn("Full name"), { exact: true }).fill("কম্বো ক্রেতা");
  await page.getByLabel(bn("Mobile number"), { exact: true }).fill("01711223344");
  await page.getByLabel(bn("Full delivery address")).fill("বাসা ১২, ধানমন্ডি, ঢাকা");
  await page.getByRole("checkbox").last().check();
  await page.getByRole("button", { name: /অর্ডার দিন/ }).click();
  await expect(page).toHaveURL(/checkout$/);
  await expect(page.locator(".toast-stack")).toContainText("কম্বো অফারটি বদলেছে অথবা শেষ হয়েছে");
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("nirbhor-v1-orders")!).length)).toBe(4);
  await page.goto("/cart");
  await page.getByRole("button", { name: "সকালের সঙ্গী সরান", exact: true }).click();
  await expect(page.locator(".combo-cart-group")).toHaveCount(0);
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("nirbhor-v1-cart")!).length)).toBe(0);
});
