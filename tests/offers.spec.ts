import { test, expect } from "@playwright/test";
import { bn } from "../src/bn";
import { cartTotals } from "../src/store";
import { seedProducts, seedSettings } from "../src/data";
import { comboAvailable, offerActive, seedCombos } from "../src/promotions";
import type { DiscountRule } from "../src/promotions";

test("offer dates, caps, exclusions and stacking follow the configured rules", () => {
  expect(offerActive({ active: true, start: "2026-10-27", end: "2026-10-27" }, Date.parse("2026-10-26T18:00:00Z"))).toBe(true);
  expect(offerActive({ active: true, start: "2026-10-27", end: "2026-10-27" }, Date.parse("2026-10-27T18:00:00Z"))).toBe(false);
  const rule: DiscountRule = { id: "test", name: "Test", type: "Percentage", value: 25, scope: "Product: p2", minimum: 800, maxDiscount: 100, start: "", end: "", active: true, allowCoupon: false, excludeSale: false };
  const items = [{ id: "p2", variant: "250g", quantity: 1 }];
  const coupon = { id: "c", code: "TEST", type: "Percentage", value: 10, minimum: 0, active: true, uses: 0, limit: 100, start: "", end: "", scope: "All products", perUser: 10 };
  expect(cartTotals(items, seedProducts, seedSettings, "Dhaka", coupon, { combos: [], discounts: [rule] })).toMatchObject({ total: 850, discount: 100, couponDiscount: 0 });
  expect(cartTotals(items, seedProducts, seedSettings, "Dhaka", coupon, { combos: [], discounts: [{ ...rule, allowCoupon: true }] })).toMatchObject({ total: 771, discount: 179, couponDiscount: 79 });
  expect(cartTotals(items, seedProducts, seedSettings, "Dhaka", undefined, { combos: [], discounts: [{ ...rule, excludeSale: true }] }).discount).toBe(0);
  expect(cartTotals(items, seedProducts, seedSettings, "Dhaka", { ...coupon, maxDiscount: 25 }).couponDiscount).toBe(25);
  const competing = { ...rule, id: "other", type: "Fixed amount" as const, value: 60, maxDiscount: 0 };
  expect(cartTotals(items, seedProducts, seedSettings, "Dhaka", undefined, { combos: [], discounts: [competing, rule] }).discount).toBe(100);
  const stock = seedProducts.map(p => p.id === "p2" ? { ...p, stock: 1 } : p);
  expect(comboAvailable(seedCombos[0], stock, items)).toBe(false);
});

