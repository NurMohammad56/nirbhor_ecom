test("admin review lifecycle updates public ratings and preserves its source label", async ({ page }) => {
  await page.goto("/admin/product-pages?product=p20");
  await page.getByRole("tab", { name: "রিভিউ", exact: true }).click();
  await page.getByRole("button", { name: "রিভিউ যোগ করুন", exact: true }).click();
  await page.getByLabel("রিভিউদাতার নাম", { exact: true }).fill("রুবিনা");
  await page.getByLabel("রিভিউ রেটিং", { exact: true }).selectOption("4");
  await page.getByLabel("রিভিউয়ের শিরোনাম", { exact: true }).fill("প্যাকিং ভালো ছিল");
  await page.getByLabel("মতামত", { exact: true }).fill("পণ্যটি ভালোভাবে প্যাক করে পাঠানো হয়েছে।");
  await page.getByLabel("রিভিউ প্রকাশের অবস্থা", { exact: true }).selectOption("Approved");
  await page.getByLabel("হোমপেজের জন্য নির্বাচন করুন", { exact: true }).check();
  await page.getByRole("button", { name: "রিভিউ সেভ করুন", exact: true }).click();
  await page.goto("/beauty/product/p20");
  await expect(page.locator(".pdp-rating")).toContainText("১টি রিভিউ");
  await expect(page.locator(".pdp-rating b")).toHaveText("৪.০");
  await expect(page.locator(".review-row")).toContainText("স্টোর থেকে যোগ করা");
  await expect(page.locator(".review-row")).not.toContainText(bn("Verified purchase"));
  await page.goto("/admin/reviews");
  await page.getByRole("button", { name: "প্যাকিং ভালো ছিল সম্পাদনা করুন", exact: true }).click();
  await page.getByLabel("রিভিউ রেটিং", { exact: true }).selectOption("2");
  await page.getByLabel("স্টোরের উত্তর", { exact: true }).fill("আপনার মতামতের জন্য ধন্যবাদ।");
  await page.getByRole("button", { name: "রিভিউ সেভ করুন", exact: true }).click();
  await page.goto("/beauty/product/p20");
  await expect(page.locator(".pdp-rating b")).toHaveText("২.০");
  await expect(page.locator(".review-row")).toContainText("আপনার মতামতের জন্য ধন্যবাদ।");
  await page.goto("/admin/reviews");
  await page.getByRole("button", { name: "প্যাকিং ভালো ছিল সম্পাদনা করুন", exact: true }).click();
  await page.getByLabel("রিভিউ প্রকাশের অবস্থা", { exact: true }).selectOption("Rejected");
  await page.getByRole("button", { name: "রিভিউ সেভ করুন", exact: true }).click();
  await page.goto("/beauty/product/p20");
  await expect(page.locator(".review-row")).toHaveCount(0);
  await expect(page.locator(".pdp-rating")).toContainText("এখনও রিভিউ নেই");
  await page.goto("/admin/reviews");
  await page.getByRole("button", { name: "প্যাকিং ভালো ছিল মুছুন", exact: true }).click();
  await page.getByRole("button", { name: "রিভিউ মুছে ফেলুন", exact: true }).click();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem("nirbhor-v1-reviews")!).some((r: {title:string}) => r.title === "প্যাকিং ভালো ছিল"))).toBe(false);
});

